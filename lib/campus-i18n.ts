export function translateCampusText(value: string, language: CampusLanguage): string {
  if (language === 'ja') return value;
  return TRANSLATIONS[language][value] ?? value;
}

export function getBrowserCampusLanguage(browserLanguage?: string | null): CampusLanguage {
  const value = String(browserLanguage || '').toLowerCase();
  if (value.startsWith('ar')) return 'ar';
  if (value.startsWith('ko')) return 'ko';
  if (value.startsWith('zh')) return 'zh';
  if (value.startsWith('en')) return 'en';
  return 'ja';
}
