type HumorKind = 'pun' | 'joke' | 'gag';
type HumorEntry = { frame: string; item: string | readonly [string, string] };

function makeBank(items: readonly (string | readonly [string, string])[], kind: HumorKind): HumorEntry[] {
  return frames[kind].flatMap(frame => items.map(item => ({ frame, item }))).slice(0, 200);
}

const banks: Record<HumorKind, HumorEntry[]> = {
  pun: makeBank(punItems, 'pun'),
  joke: makeBank(jokeItems, 'joke'),
  gag: makeBank(gagItems, 'gag'),
};

function choose<T>(items: readonly T[]): T {
  return items[Math.floor(Math.random() * items.length)];
}

export function getLineHumorAnswer(question: string): { kind: HumorKind; answer: string } | null {
  const normalized = question.normalize('NFKC').replace(/[\s　]+/gu, '').toLowerCase();
  const kind: HumorKind | null =
    /だじゃれ|ダジャレ|駄洒落/.test(normalized) ? 'pun' :
    /一発芸|ひとつ芸|ギャグして|芸をして/.test(normalized) ? 'gag' :
    /面白いこと|おもしろいこと|笑わせて|笑える話|ネタを言|何か面白/.test(normalized) ? 'joke' :
    null;
  if (!kind) return null;

  const entry = choose(banks[kind]);
  const content = typeof entry.item === 'string'
    ? entry.item
    : 'Q. ' + entry.item[0] + '\nA. ' + entry.item[1];
  return {
    kind,
    answer: entry.frame + '\n\n' + content,
  };
}
