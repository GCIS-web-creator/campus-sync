-- CampusSync: 5 LINE公式アカウントを月の日数に合わせて均等ローテーション
-- ローテーション順: BOT4 -> BOT5 -> BOT1 -> BOT2 -> BOT3 -> BOT4 ...（2026-11-09開始）
-- 30日月: BOT3=1〜6日 / BOT4=7〜12日 / BOT5=13〜18日 / BOT1=19〜24日 / BOT2=25〜30日
-- 31日月: 同じ順で各6日、最後のBOT2が7日。28・29日月も5アカウントにできるだけ均等配分。
-- Supabase pg_cron (UTC): 23:55 UTC = 08:55 JST. The current delivery BOT stays active until Admin confirms the group handoff.
-- Tokens and Channel Secrets are stored only in Vercel environment variables.
-- Admin UI receives slot/status only; no credential values are ever stored in Supabase.

create extension if not exists pg_cron with schema pg_catalog;

create table if not exists public.line_bot_rotation (
  id smallint primary key default 1 check (id = 1),
  active_bot_slot smallint not null check (active_bot_slot between 1 and 5),
  next_switch_at timestamptz not null,
  last_switched_at timestamptz,
  rotation_hold_until date,
  handoff_group_chat_id text,
  updated_at timestamptz not null default now()
);

alter table public.line_bot_rotation
  add column if not exists rotation_hold_until date;
alter table public.line_bot_rotation
  add column if not exists handoff_group_chat_id text;

create table if not exists public.line_bot_rotation_events (
  id bigint generated by default as identity primary key,
  previous_bot_slot smallint check (previous_bot_slot between 1 and 5),
  new_bot_slot smallint not null check (new_bot_slot between 1 and 5),
  effective_date date not null,
  created_at timestamptz not null default now(),
  acknowledged_at timestamptz
);

-- Widen existing installations too; CREATE TABLE IF NOT EXISTS does not alter old checks.
alter table public.line_bot_rotation
  drop constraint if exists line_bot_rotation_active_bot_slot_check;
alter table public.line_bot_rotation
  add constraint line_bot_rotation_active_bot_slot_check check (active_bot_slot between 1 and 5);

alter table public.line_bot_rotation_events
  drop constraint if exists line_bot_rotation_events_previous_bot_slot_check;
alter table public.line_bot_rotation_events
  add constraint line_bot_rotation_events_previous_bot_slot_check check (previous_bot_slot between 1 and 5);

alter table public.line_bot_rotation_events
  drop constraint if exists line_bot_rotation_events_new_bot_slot_check;
alter table public.line_bot_rotation_events
  add constraint line_bot_rotation_events_new_bot_slot_check check (new_bot_slot between 1 and 5);

create index if not exists line_bot_rotation_events_pending_idx
  on public.line_bot_rotation_events (created_at desc)
  where acknowledged_at is null;

alter table public.line_bot_rotation enable row level security;
alter table public.line_bot_rotation_events enable row level security;
revoke all on public.line_bot_rotation from anon, authenticated;
revoke all on public.line_bot_rotation_events from anon, authenticated;
grant all on public.line_bot_rotation to service_role;
grant all on public.line_bot_rotation_events to service_role;
grant usage, select on sequence public.line_bot_rotation_events_id_seq to service_role;

create or replace function public.campussync_refresh_line_bot_rotation()
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  v_today date := (now() at time zone 'Asia/Tokyo')::date;
  v_month_start date;
  v_days_in_month integer;
  v_day integer;
  v_period integer;
  v_slot smallint;
  v_next_date date;
  v_next_switch timestamptz;
  v_previous_slot smallint;
  v_hold_until date;
begin
  v_month_start := date_trunc('month', v_today::timestamp)::date;
  v_days_in_month := extract(day from (v_month_start + interval '1 month' - interval '1 day'))::integer;

  select active_bot_slot, rotation_hold_until
    into v_previous_slot, v_hold_until
    from public.line_bot_rotation
   where id = 1
   for update;

  v_day := extract(day from v_today)::integer;

  if v_hold_until is not null and v_today <= v_hold_until then
    -- Keep the configured account until the one-time hold date has passed.
    v_slot := v_previous_slot;
    v_next_date := v_hold_until + 1;
  else
    -- Five nearly equal monthly periods, assigned BOT 3 -> 4 -> 5 -> 1 -> 2.
    v_period := least(5, ceil(v_day * 5.0 / v_days_in_month)::integer);

    if v_period < 5 then
      v_next_date := v_month_start + floor(v_period * v_days_in_month / 5.0)::integer;
    else
      v_next_date := (v_month_start + interval '1 month')::date;
    end if;

    v_slot := (((v_period + 1) % 5) + 1)::smallint;
  end if;

  v_next_switch := (v_next_date + time '09:00') at time zone 'Asia/Tokyo';

  if not found then
    insert into public.line_bot_rotation (
      id, active_bot_slot, next_switch_at, last_switched_at, updated_at
    ) values (
      1, v_slot, v_next_switch, now(), now()
    );
    insert into public.line_bot_rotation_events (
      previous_bot_slot, new_bot_slot, effective_date
    ) values (
      null, v_slot, v_today
    );
    return;
  end if;

  if v_previous_slot is distinct from v_slot then
    update public.line_bot_rotation
       set active_bot_slot = v_slot,
           next_switch_at = v_next_switch,
           rotation_hold_until = case when v_hold_until is not null and v_today > v_hold_until then null else v_hold_until end,
           last_switched_at = now(),
           updated_at = now()
     where id = 1;

    insert into public.line_bot_rotation_events (
      previous_bot_slot, new_bot_slot, effective_date
    ) values (
      v_previous_slot, v_slot, v_today
    );
  else
    update public.line_bot_rotation
       set next_switch_at = v_next_switch,
           rotation_hold_until = case when v_hold_until is not null and v_today > v_hold_until then null else v_hold_until end,
           updated_at = now()
     where id = 1;
  end if;
end;
$function$;

revoke all on function public.campussync_refresh_line_bot_rotation() from public, anon, authenticated;
grant execute on function public.campussync_refresh_line_bot_rotation() to service_role;

-- Current installations use a manual, group-confirmed switch. This idempotent block
-- is intentionally placed before the initial refresh call below so re-running this
-- setup script will not restore the former time-only automatic switch.
